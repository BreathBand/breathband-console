import type { SkillLevel } from "../config";
import type { PacedTransitionType, PacedUserTransition } from "../paced";

export interface TierADerivation {
  readonly pacerT: number;
  readonly type: PacedTransitionType;
  readonly status: "single" | "missed" | "double";
  readonly matchT: readonly number[];
  readonly deltaTimeS: number | null;
  readonly dTime: number | null;
  readonly eTime: number | null;
  readonly timingPoints: number;
  readonly deltaDepthPct: number | null;
  readonly dDepth: number | null;
  readonly eDepth: number | null;
  readonly depthPoints: number;
}

export interface TierAInhaleExhale {
  readonly inhale: number;
  readonly exhale: number;
}

export interface TierAExpected {
  readonly scores: { readonly timing: TierAInhaleExhale; readonly depth: TierAInhaleExhale; readonly total: number };
  readonly onTargetPct: { readonly timing: number; readonly depth: number };
  readonly direction: {
    readonly timing: { readonly inhale: { readonly sd: number; readonly s: number }; readonly exhale: { readonly sd: number; readonly s: number } };
    readonly depth: {
      readonly inhale: { readonly sd: number; readonly pctOfMax: number };
      readonly exhale: { readonly sd: number; readonly pctOfMax: number };
    };
  };
  readonly histogram: { readonly timing: readonly number[]; readonly depth: readonly number[]; readonly missedOrDouble: number };
  readonly counts: { readonly missed: number; readonly double: number; readonly pacer: number };
  readonly timingPoints: { readonly inhale: readonly number[]; readonly exhale: readonly number[] };
}

export interface TierACase {
  readonly halfCycleS: number;
  readonly durationS: number;
  readonly skillLevel: SkillLevel;
  readonly inputs: readonly PacedUserTransition[];
  readonly derivation: readonly TierADerivation[];
  readonly expected: TierAExpected;
}

